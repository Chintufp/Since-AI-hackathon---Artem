/** Replace every <i data-icon="name"> below `root` with the matching inline SVG. */
export function hydrateIcons(root: ParentNode): void {
  root.querySelectorAll<HTMLElement>('i[data-icon]').forEach((el) => {
    el.outerHTML = iconSvg(el.dataset.icon ?? '');
  });
}
